// Data and profile JSON remain TEXT to preserve the existing SQLite API shape.
// Epoch times use BIGINT; sessions keep numeric INTEGER identifiers.
export const postgresSchema = `
  CREATE TABLE IF NOT EXISTS products (id INTEGER PRIMARY KEY, data TEXT NOT NULL);
  CREATE TABLE IF NOT EXISTS doctors (rowid BIGSERIAL UNIQUE, id TEXT PRIMARY KEY, data TEXT NOT NULL);
  CREATE TABLE IF NOT EXISTS sessions (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash TEXT NOT NULL UNIQUE, expires_at BIGINT NOT NULL,
    profile TEXT NOT NULL DEFAULT '{}', location_pin TEXT NOT NULL DEFAULT '',
    newsletter_email TEXT NOT NULL DEFAULT ''
  );
  CREATE TABLE IF NOT EXISTS cart (
    session_id INTEGER NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    product_id INTEGER NOT NULL REFERENCES products(id),
    quantity INTEGER NOT NULL CHECK(quantity BETWEEN 1 AND 99),
    PRIMARY KEY(session_id,product_id)
  );
  CREATE TABLE IF NOT EXISTS orders (
    rowid BIGSERIAL UNIQUE, id TEXT PRIMARY KEY,
    session_id INTEGER NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    idempotency_key TEXT NOT NULL, request_hash TEXT NOT NULL,
    data TEXT NOT NULL, created_at TEXT NOT NULL,
    UNIQUE(session_id,idempotency_key)
  );
  CREATE TABLE IF NOT EXISTS appointments (
    rowid BIGSERIAL UNIQUE, id TEXT PRIMARY KEY,
    session_id INTEGER NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    doctor_id TEXT NOT NULL REFERENCES doctors(id), patient TEXT NOT NULL,
    date TEXT NOT NULL, time TEXT NOT NULL, fee INTEGER NOT NULL,
    status TEXT NOT NULL CHECK(status IN ('Booked','Cancelled')), created_at TEXT NOT NULL
  );
  CREATE UNIQUE INDEX IF NOT EXISTS one_active_appointment
    ON appointments(doctor_id,date,time) WHERE status = 'Booked';
  CREATE TABLE IF NOT EXISTS prescriptions (
    rowid BIGSERIAL UNIQUE, id TEXT PRIMARY KEY,
    session_id INTEGER NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    name TEXT NOT NULL, mime TEXT NOT NULL, size INTEGER NOT NULL,
    created_at TEXT NOT NULL, content BYTEA NOT NULL
  );
  CREATE TABLE IF NOT EXISTS users (
    id TEXT PRIMARY KEY, owner_id INTEGER NOT NULL UNIQUE REFERENCES sessions(id),
    name TEXT NOT NULL DEFAULT '', email TEXT, phone TEXT, created_at BIGINT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS auth_identities (
    provider TEXT NOT NULL CHECK(provider IN ('google','mobile')), subject TEXT NOT NULL,
    user_id TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    PRIMARY KEY(provider,subject), UNIQUE(user_id,provider)
  );
  CREATE TABLE IF NOT EXISTS browser_sessions (
    id TEXT PRIMARY KEY, owner_id INTEGER NOT NULL REFERENCES sessions(id),
    user_id TEXT REFERENCES users(id), token_hash TEXT NOT NULL UNIQUE, expires_at BIGINT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS otp_challenges (
    id TEXT PRIMARY KEY, browser_id TEXT NOT NULL REFERENCES browser_sessions(id) ON DELETE CASCADE,
    mobile TEXT NOT NULL, mode TEXT NOT NULL CHECK(mode IN ('login','link')),
    expires_at BIGINT NOT NULL, attempts INTEGER NOT NULL DEFAULT 0,
    status TEXT NOT NULL CHECK(status IN ('sending','pending','verifying','consumed','failed')),
    created_at BIGINT NOT NULL
  );
  CREATE TABLE IF NOT EXISTS auth_rate_limits (
    scope TEXT NOT NULL, key TEXT NOT NULL, window_start BIGINT NOT NULL,
    count INTEGER NOT NULL, last_sent BIGINT NOT NULL, PRIMARY KEY(scope,key)
  );
  CREATE TABLE IF NOT EXISTS widget_token_uses (
    token_hash TEXT PRIMARY KEY, browser_id TEXT NOT NULL,
    created_at BIGINT NOT NULL, expires_at BIGINT NOT NULL,
    status TEXT NOT NULL CHECK(status IN ('verifying','consumed','failed'))
  );
  CREATE INDEX IF NOT EXISTS widget_token_expiry ON widget_token_uses(expires_at);
  CREATE TABLE IF NOT EXISTS schema_migrations (version INTEGER PRIMARY KEY);
`;
